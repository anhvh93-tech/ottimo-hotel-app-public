-- K14-L – booking list behind the K14 counts (DOM FB-R5-DOM-ARC-1H-01, SEC FB-R5-SEC-ARC-1I-02, contract 0.3.13 1.30).
-- Runbook v1.0.5 K14, part "Danh sach". Run ONLY when K14 printed a list count > 0 and the investor agreed to this run,
-- ONLY through the k14-list-run block that SEC pinned, as ottimo_readonly, and ONLY in the investor's own terminal:
-- the output never goes into the repo, a PR, a commit, a chat, a subagent, a file or a log.
-- READ ONLY, ends with ROLLBACK. Prints per booking: list tag, booking code, booking status, property dates, counts,
-- role names, commission row statuses and fixed tags. Never a person's name, a username, an id (uuid), an amount, a
-- rate, a reason text or a guest column: the investor opens the booking on the Desk to see who (booking history,
-- Commission screen). Do not edit this file, not even a comment: one byte changes its SHA-256.
BEGIN TRANSACTION READ ONLY;
SELECT 1 AS guard
 WHERE (CASE
          WHEN NOT COALESCE((SELECT r.rolbypassrls OR r.rolsuper FROM pg_roles r WHERE r.rolname = current_user), false)
               AND COALESCE(current_setting('app.property_id', true), '') = ''
            THEN 'k14 list stopped: run as ottimo_readonly (BYPASSRLS) - under RLS without a tenant nothing shows'
          WHEN NOT EXISTS (SELECT 1 FROM property)
            THEN 'k14 list stopped: no property is visible'
          ELSE 'false'
        END)::boolean;
-- (1) List 1: l1|code|status|checked in on|changes after check-in|last change on|roles now of who made the last
--     change (system / revoked / none)|live commission row statuses (none)|live payee is the closer (yes/no/none)|
--     what to do: before_checkout (in_house), next_payout (checked_out), check (other).
WITH c AS (
  SELECT ch.reservation_id AS booking, ch.property_id, ch.changed_at, ch.changed_by,
         row_number() OVER (PARTITION BY ch.reservation_id ORDER BY ch.changed_at DESC, ch.id DESC) AS k,
         count(*) OVER (PARTITION BY ch.reservation_id) AS n
    FROM reservation_change ch
    JOIN reservation rv ON rv.id = ch.reservation_id AND rv.property_id = ch.property_id
   WHERE ch.field = 'closer_user_id'
     AND rv.actual_checkin_at IS NOT NULL
     AND ch.changed_at >= rv.actual_checkin_at
)
SELECT 'l1' AS list, rv.code, rv.status,
       (rv.actual_checkin_at AT TIME ZONE p.timezone)::date::text AS checked_in_on,
       c.n AS changes_after_checkin,
       (c.changed_at AT TIME ZONE p.timezone)::date::text AS last_change_on,
       CASE WHEN c.changed_by IS NULL THEN 'system'
            ELSE COALESCE((SELECT string_agg(DISTINCT u.role, '+' ORDER BY u.role) FROM user_property_role u
                            WHERE u.user_id = c.changed_by AND u.property_id = c.property_id AND u.revoked_at IS NULL),
                          (SELECT 'revoked' FROM user_property_role u
                            WHERE u.user_id = c.changed_by AND u.property_id = c.property_id LIMIT 1),
                          'none') END AS changer_roles_now,
       COALESCE((SELECT string_agg(DISTINCT cm.status, '+' ORDER BY cm.status) FROM commission cm
                  WHERE cm.reservation_id = rv.id AND cm.property_id = rv.property_id AND cm.status <> 'void'),
                'none') AS live_rows,
       CASE WHEN NOT EXISTS (SELECT 1 FROM commission cm
                              WHERE cm.reservation_id = rv.id AND cm.property_id = rv.property_id
                                AND cm.status <> 'void') THEN 'none'
            WHEN EXISTS (SELECT 1 FROM commission cm
                          WHERE cm.reservation_id = rv.id AND cm.property_id = rv.property_id AND cm.status <> 'void'
                            AND cm.payee_user_id IS DISTINCT FROM rv.closer_user_id) THEN 'no'
            ELSE 'yes' END AS live_payee_is_closer,
       CASE rv.status WHEN 'in_house' THEN 'before_checkout' WHEN 'checked_out' THEN 'next_payout'
                      ELSE 'check' END AS todo
  FROM c
  JOIN reservation rv ON rv.id = c.booking AND rv.property_id = c.property_id
  JOIN property p ON p.id = rv.property_id
 WHERE c.k = 1
 ORDER BY CASE rv.status WHEN 'in_house' THEN 1 WHEN 'checked_out' THEN 2 ELSE 3 END, rv.code;
-- (2) List 2: l2|code|status|statuses of the live rows whose payee is not the closer|last closer change
--     (after_checkin / before_checkin / none)|what to do: next_payout (a row earned, payable or paid),
--     desk_fixes_at_checkout (projected only, booking not checked out, not cancelled or no-show, not in list 1),
--     check (any other case).
WITH m AS (
  SELECT rv.id AS booking, string_agg(DISTINCT cm.status, '+' ORDER BY cm.status) AS row_statuses,
         bool_or(cm.status IN ('earned', 'payable', 'paid')) AS any_earned
    FROM commission cm
    JOIN reservation rv ON rv.id = cm.reservation_id AND rv.property_id = cm.property_id
   WHERE cm.reservation_id IS NOT NULL AND cm.status <> 'void'
     AND cm.payee_user_id IS DISTINCT FROM rv.closer_user_id
   GROUP BY rv.id
), x AS (
  SELECT m.booking, m.row_statuses, m.any_earned, rv.code, rv.status,
         (SELECT CASE WHEN rv.actual_checkin_at IS NOT NULL AND ch.changed_at >= rv.actual_checkin_at
                      THEN 'after_checkin' ELSE 'before_checkin' END
            FROM reservation_change ch
           WHERE ch.reservation_id = rv.id AND ch.property_id = rv.property_id AND ch.field = 'closer_user_id'
           ORDER BY ch.changed_at DESC, ch.id DESC
           LIMIT 1) AS last_change,
         EXISTS (SELECT 1 FROM reservation_change ch
                  WHERE ch.reservation_id = rv.id AND ch.property_id = rv.property_id
                    AND ch.field = 'closer_user_id'
                    AND rv.actual_checkin_at IS NOT NULL AND ch.changed_at >= rv.actual_checkin_at) AS in_l1
    FROM m
    JOIN reservation rv ON rv.id = m.booking
)
SELECT 'l2' AS list, x.code, x.status, x.row_statuses, COALESCE(x.last_change, 'none') AS last_closer_change,
       CASE WHEN x.any_earned THEN 'next_payout'
            WHEN x.status IN ('hold', 'confirmed', 'in_house') AND NOT x.in_l1 THEN 'desk_fixes_at_checkout'
            ELSE 'check' END AS todo
  FROM x
 ORDER BY CASE WHEN x.any_earned THEN 1
               WHEN x.status IN ('hold', 'confirmed', 'in_house') AND NOT x.in_l1 THEN 3
               ELSE 2 END, x.code;
ROLLBACK;
