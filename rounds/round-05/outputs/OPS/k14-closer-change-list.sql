-- K14-L – booking list behind the K14 counts (DOM FB-R5-DOM-ARC-1H-01, DOM FB-R5-DOM-OPS-155-01 and 155-03,
-- SEC FB-R5-SEC-ARC-1I-02, contract 0.3.13 1.30). Runbook v1.0.5 K14, part "Danh sach".
-- Run ONLY when K14 printed a list count > 0 and the investor agreed to this run, ONLY through the k14-list-run block
-- that SEC pinned, as ottimo_readonly, and ONLY in the investor's own terminal: the output never goes into the repo,
-- a PR, a commit, a chat, a subagent, a file or a log.
-- READ ONLY, ends with ROLLBACK. Prints per booking: list tag, booking code, stay type, child booking or not, status,
-- property dates, counts, STAFF DISPLAY NAMES (the Desk v1.0.5 shows the investor no closer and no commission payee -
-- DOM 155-01; filtered as SEC 155-03), role names, commission row statuses and fixed tags. Never a username, an
-- email, a phone, an id (uuid), an amount, a rate, a reason text or a guest column. Do not edit this file, not even
-- a comment: one byte changes its SHA-256.
BEGIN TRANSACTION READ ONLY;
SELECT 1 AS guard
 WHERE (CASE
          WHEN NOT COALESCE((SELECT r.rolbypassrls OR r.rolsuper FROM pg_roles r WHERE r.rolname = current_user), false)
               AND COALESCE(current_setting('app.property_id', true), '') = ''
            THEN 'k14 list stopped: run as ottimo_readonly (BYPASSRLS) - under RLS without a tenant nothing shows'
          WHEN NOT EXISTS (SELECT 1 FROM property)
            THEN 'k14 list stopped: no property is visible'
          ELSE 'false'
        END)::boolean;
-- Staff name as printed (SEC FB-R5-SEC-OPS-155-03): app_user.display_name of the booking's organization only; control
-- (C0, DEL, C1), invisible, bidi and | characters become ?, written as \x / \u escapes so no invisible character sits in this file;
-- cut at 80 characters; then " (đã thu hồi)" when every role of the person at that property is revoked. A user id is
-- compared as text (uuid::text = old_value), never cast, so no error message can repeat a value. Unknown id ->
-- 'unknown'; no person (system change, empty closer) -> 'none'.
-- (1) List 1: l1|code|stay type|child|status|checked in on|changes after check-in|last change on|closer at check-in
--     (the earlier value of the FIRST change from check-in)|closer now|who made the last change (none)|their roles
--     now (system / revoked / none)|live commission rows as name:status (none)|live payee is the closer (yes/no/none)|
--     what to do: before_checkout (in_house), next_payout (checked_out), check (other).
WITH staff AS (
  SELECT p.id AS property_id, a.id AS user_id,
         left(regexp_replace(a.display_name,
                '[\x01-\x1f\x7f-\x9f\u00ad\u061c\u180e\u200b-\u200f\u2028-\u202e\u2060-\u206f\ufeff\ufff9-\ufffb|]',
                '?', 'g'), 80)
           || CASE WHEN EXISTS (SELECT 1 FROM user_property_role u WHERE u.user_id = a.id AND u.property_id = p.id)
                    AND NOT EXISTS (SELECT 1 FROM user_property_role u
                                     WHERE u.user_id = a.id AND u.property_id = p.id AND u.revoked_at IS NULL)
                   THEN ' (đã thu hồi)' ELSE '' END AS tag
    FROM app_user a
    JOIN property p ON p.organization_id = a.organization_id
), c AS (
  SELECT ch.reservation_id AS booking, ch.property_id, ch.changed_at, ch.changed_by, ch.old_value,
         row_number() OVER (PARTITION BY ch.reservation_id ORDER BY ch.changed_at DESC, ch.id DESC) AS k_last,
         row_number() OVER (PARTITION BY ch.reservation_id ORDER BY ch.changed_at, ch.id) AS k_first,
         count(*) OVER (PARTITION BY ch.reservation_id) AS n
    FROM reservation_change ch
    JOIN reservation rv ON rv.id = ch.reservation_id AND rv.property_id = ch.property_id
   WHERE ch.field = 'closer_user_id'
     AND rv.actual_checkin_at IS NOT NULL
     AND ch.changed_at >= rv.actual_checkin_at
)
SELECT 'l1' AS list, rv.code, rv.stay_type,
       CASE WHEN rv.parent_reservation_id IS NULL THEN 'main' ELSE 'child' END AS booking_kind,
       rv.status,
       (rv.actual_checkin_at AT TIME ZONE p.timezone)::date::text AS checked_in_on,
       c.n AS changes_after_checkin,
       (c.changed_at AT TIME ZONE p.timezone)::date::text AS last_change_on,
       (SELECT CASE WHEN f.old_value IS NULL THEN 'none'
                    ELSE COALESCE((SELECT s.tag FROM staff s
                                    WHERE s.property_id = f.property_id AND s.user_id::text = f.old_value),
                                  'unknown') END
          FROM c f WHERE f.booking = c.booking AND f.k_first = 1) AS closer_at_checkin,
       CASE WHEN rv.closer_user_id IS NULL THEN 'none'
            ELSE COALESCE((SELECT s.tag FROM staff s
                            WHERE s.property_id = rv.property_id AND s.user_id = rv.closer_user_id), 'unknown')
            END AS closer_now,
       CASE WHEN c.changed_by IS NULL THEN 'none'
            ELSE COALESCE((SELECT s.tag FROM staff s
                            WHERE s.property_id = c.property_id AND s.user_id = c.changed_by), 'unknown')
            END AS last_changed_by,
       CASE WHEN c.changed_by IS NULL THEN 'system'
            ELSE COALESCE((SELECT string_agg(DISTINCT u.role, '+' ORDER BY u.role) FROM user_property_role u
                            WHERE u.user_id = c.changed_by AND u.property_id = c.property_id AND u.revoked_at IS NULL),
                          (SELECT 'revoked' FROM user_property_role u
                            WHERE u.user_id = c.changed_by AND u.property_id = c.property_id LIMIT 1),
                          'none') END AS last_changer_roles_now,
       COALESCE((SELECT string_agg(DISTINCT COALESCE(s.tag, 'unknown') || ':' || cm.status, '+')
                   FROM commission cm
                   LEFT JOIN staff s ON s.property_id = cm.property_id AND s.user_id = cm.payee_user_id
                  WHERE cm.reservation_id = rv.id AND cm.property_id = rv.property_id AND cm.status <> 'void'),
                'none') AS live_rows,
       CASE WHEN NOT EXISTS (SELECT 1 FROM commission cm
                              WHERE cm.reservation_id = rv.id AND cm.property_id = rv.property_id
                                AND cm.status <> 'void') THEN 'none'
            WHEN EXISTS (SELECT 1 FROM commission cm
                          WHERE cm.reservation_id = rv.id AND cm.property_id = rv.property_id AND cm.status <> 'void'
                            AND cm.payee_user_id IS DISTINCT FROM rv.closer_user_id) THEN 'no'
            ELSE 'yes' END AS live_payee_is_closer,
       CASE rv.status WHEN 'in_house' THEN 'before_checkout' WHEN 'checked_out' THEN 'next_payout'
                      ELSE 'check' END AS todo
  FROM c
  JOIN reservation rv ON rv.id = c.booking AND rv.property_id = c.property_id
  JOIN property p ON p.id = rv.property_id
 WHERE c.k_last = 1
 ORDER BY CASE rv.status WHEN 'in_house' THEN 1 WHEN 'checked_out' THEN 2 ELSE 3 END, rv.code;
-- (2) List 2: l2|code|stay type|child|status|live rows whose payee is not the closer, as name:status|closer now|
--     last closer change (after_checkin / before_checkin / none)|what to do: next_payout (a row earned, payable or
--     paid), desk_fixes_at_checkout (projected only, booking hold / confirmed / in_house, not in list 1),
--     desk_fixes_when_earned (projected only, checked out, not in list 1: every earning path re-syncs it - DOM 155-03),
--     check (any other case).
WITH staff AS (
  SELECT p.id AS property_id, a.id AS user_id,
         left(regexp_replace(a.display_name,
                '[\x01-\x1f\x7f-\x9f\u00ad\u061c\u180e\u200b-\u200f\u2028-\u202e\u2060-\u206f\ufeff\ufff9-\ufffb|]',
                '?', 'g'), 80)
           || CASE WHEN EXISTS (SELECT 1 FROM user_property_role u WHERE u.user_id = a.id AND u.property_id = p.id)
                    AND NOT EXISTS (SELECT 1 FROM user_property_role u
                                     WHERE u.user_id = a.id AND u.property_id = p.id AND u.revoked_at IS NULL)
                   THEN ' (đã thu hồi)' ELSE '' END AS tag
    FROM app_user a
    JOIN property p ON p.organization_id = a.organization_id
), m AS (
  SELECT rv.id AS booking,
         string_agg(DISTINCT COALESCE(s.tag, 'unknown') || ':' || cm.status, '+') AS rows_not_closer,
         bool_or(cm.status IN ('earned', 'payable', 'paid')) AS any_earned
    FROM commission cm
    JOIN reservation rv ON rv.id = cm.reservation_id AND rv.property_id = cm.property_id
    LEFT JOIN staff s ON s.property_id = cm.property_id AND s.user_id = cm.payee_user_id
   WHERE cm.reservation_id IS NOT NULL AND cm.status <> 'void'
     AND cm.payee_user_id IS DISTINCT FROM rv.closer_user_id
   GROUP BY rv.id
), x AS (
  SELECT m.booking, m.rows_not_closer, m.any_earned, rv.code, rv.stay_type, rv.status,
         CASE WHEN rv.parent_reservation_id IS NULL THEN 'main' ELSE 'child' END AS booking_kind,
         CASE WHEN rv.closer_user_id IS NULL THEN 'none'
              ELSE COALESCE((SELECT s.tag FROM staff s
                              WHERE s.property_id = rv.property_id AND s.user_id = rv.closer_user_id), 'unknown')
              END AS closer_now,
         (SELECT CASE WHEN rv.actual_checkin_at IS NOT NULL AND ch.changed_at >= rv.actual_checkin_at
                      THEN 'after_checkin' ELSE 'before_checkin' END
            FROM reservation_change ch
           WHERE ch.reservation_id = rv.id AND ch.property_id = rv.property_id AND ch.field = 'closer_user_id'
           ORDER BY ch.changed_at DESC, ch.id DESC
           LIMIT 1) AS last_change,
         EXISTS (SELECT 1 FROM reservation_change ch
                  WHERE ch.reservation_id = rv.id AND ch.property_id = rv.property_id
                    AND ch.field = 'closer_user_id'
                    AND rv.actual_checkin_at IS NOT NULL AND ch.changed_at >= rv.actual_checkin_at) AS in_l1
    FROM m
    JOIN reservation rv ON rv.id = m.booking
), t AS (
  SELECT x.*,
         CASE WHEN x.any_earned THEN 'next_payout'
              WHEN x.status IN ('hold', 'confirmed', 'in_house') AND NOT x.in_l1 THEN 'desk_fixes_at_checkout'
              WHEN x.status = 'checked_out' AND NOT x.in_l1 THEN 'desk_fixes_when_earned'
              ELSE 'check' END AS todo
    FROM x
)
SELECT 'l2' AS list, t.code, t.stay_type, t.booking_kind, t.status, t.rows_not_closer, t.closer_now,
       COALESCE(t.last_change, 'none') AS last_closer_change, t.todo
  FROM t
 ORDER BY CASE t.todo WHEN 'next_payout' THEN 1 WHEN 'check' THEN 2 WHEN 'desk_fixes_when_earned' THEN 3 ELSE 4 END,
          t.code;
ROLLBACK;
