// Writes src/styles/fonts.css: self-hosted @font-face rules from @fontsource (OFL-1.1) – no font CDN
// (SEC C-1, ADR-014 2.5). Only the faces the landing uses (concept 3: Lora 400 + 400 italic for display text,
// Be Vietnam Pro 400/500/600 for text) and only the latin, latin-ext and vietnamese subsets (concept 12), woff2 only.
// The per-subset CSS files of @fontsource carry no unicode-range, so the ranges are copied from the combined file of
// each weight; the browser then downloads only the subsets a page's text needs.
// Run `pnpm --filter @ottimo/landing-web sync:fonts` after bumping @fontsource; src/styles/brand.test.ts fails when stale.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

export const OUT_URL = new URL('../src/styles/fonts.css', import.meta.url);
const require = createRequire(import.meta.url);

export const FACES = [
  { pkg: 'lora', family: 'Lora', style: 'normal', weight: 400 },
  { pkg: 'lora', family: 'Lora', style: 'italic', weight: 400 },
  { pkg: 'be-vietnam-pro', family: 'Be Vietnam Pro', style: 'normal', weight: 400 },
  { pkg: 'be-vietnam-pro', family: 'Be Vietnam Pro', style: 'normal', weight: 500 },
  { pkg: 'be-vietnam-pro', family: 'Be Vietnam Pro', style: 'normal', weight: 600 },
];
// For overlapping ranges the face declared LAST is tried first (CSS Fonts 4). @fontsource/Google declare
// vietnamese, latin-ext, latin – so Vietnamese letters shared with latin-ext (ă đ ĩ ũ ơ ư) pull the latin-ext file
// too. Declaring vietnamese after latin-ext lets the vietnamese file cover them alone: latin-ext is then only
// downloaded for other European letters (none on the page) – about 68 kB less on /vi/ (concept 11.2 budget).
export const SUBSETS = ['latin-ext', 'vietnamese', 'latin'];

async function combinedCss(pkg, weight, style) {
  const dir = path.dirname(require.resolve(`@fontsource/${pkg}/package.json`));
  return readFile(path.join(dir, `${weight}${style === 'italic' ? '-italic' : ''}.css`), 'utf8');
}

export async function render() {
  const rules = [];
  for (const { pkg, family, style, weight } of FACES) {
    const css = await combinedCss(pkg, weight, style);
    for (const subset of SUBSETS) {
      const id = `${pkg}-${subset}-${weight}-${style}`;
      const block = css.split(`/* ${id} */`)[1];
      const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1];
      if (!range) throw new Error(`@fontsource/${pkg}: no unicode-range for ${id}`);
      rules.push(
        `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-display: swap;\n` +
          `  font-weight: ${weight};\n  src: url('@fontsource/${pkg}/files/${id}.woff2') format('woff2');\n` +
          `  unicode-range: ${range.trim()};\n}`,
      );
    }
  }
  const source =
    '/* GENERATED by apps/landing-web/scripts/sync-fonts.mjs from @fontsource – do not edit.\n' +
    '   Lora 400 + 400 italic, Be Vietnam Pro 400/500/600; subsets latin, latin-ext, vietnamese; woff2 only. */\n' +
    rules.join('\n');
  return format(source);
}

async function format(source) {
  const options = (await prettier.resolveConfig(fileURLToPath(OUT_URL))) ?? {};
  return prettier.format(source, { ...options, parser: 'css' });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUT_URL, await render());
  console.log('src/styles/fonts.css written');
}
