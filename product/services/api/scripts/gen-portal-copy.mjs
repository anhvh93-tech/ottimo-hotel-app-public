#!/usr/bin/env node
// Generates src/generated/portal-copy.ts from design/copy/strings-vi.json (UXD owns the text): the
// Vietnamese words of the enum values the server writes into getPortalData `fields[].value` and
// `clipboardText` (gender, visa kind, empty field). The Ministry of Public Security portal expects
// Vietnamese whatever the desk UI language is (ORC 17/10, UXD s3 section 9), so there is NO fallback to
// another locale: a key missing in strings-vi.json fails the generator.
// The Docker build does not read design/, so the output is committed; `--check` (run by
// test/registration-rules.test.ts) fails when the committed file is stale.
//
//   node scripts/gen-portal-copy.mjs          write the file
//   node scripts/gen-portal-copy.mjs --check  exit 1 when the file differs from the copy
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = join(here, '..');
const copyFile = join(apiDir, '..', '..', 'design', 'copy', 'strings-vi.json');
const outPath = join(apiDir, 'src', 'generated', 'portal-copy.ts');

const KEYS = [
  'reg.value.gender.male',
  'reg.value.gender.female',
  'reg.value.gender.other',
  'reg.value.visa_kind.visa',
  'reg.value.visa_kind.visa_exempt',
  'reg.value.visa_kind.temp_residence_card',
  'reg.value.empty',
];

export async function build() {
  const vi = JSON.parse(readFileSync(copyFile, 'utf8'));
  const strings = {};
  for (const k of KEYS) {
    if (typeof vi[k] !== 'string' || vi[k].trim() === '') {
      throw new Error(`copy key ${k} missing in strings-vi.json (UXD)`);
    }
    strings[k] = vi[k];
  }
  const src =
    '// GENERATED by scripts/gen-portal-copy.mjs from design/copy/strings-vi.json – do not edit.\n' +
    '/** Vietnamese text of the portal value keys (getPortalData `fields[].value`, `clipboardText`). */\n' +
    `export const PORTAL_VALUE_VI = ${JSON.stringify(strings, null, 2)} as const;\n\n` +
    'export type PortalValueKey = keyof typeof PORTAL_VALUE_VI;\n';
  const require = createRequire(import.meta.url);
  const prettier = require('prettier');
  const config = (await prettier.resolveConfig(outPath)) ?? {};
  return prettier.format(src, { ...config, parser: 'typescript' });
}

const out = await build();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    current = '';
  }
  if (current !== out) {
    console.error('src/generated/portal-copy.ts is stale – run node scripts/gen-portal-copy.mjs');
    process.exit(1);
  }
  console.log('portal-copy.ts is up to date');
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath}`);
}
