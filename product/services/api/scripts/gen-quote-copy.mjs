#!/usr/bin/env node
// Generates src/generated/quote-copy.ts from design/copy/strings-{vi,en,ru}.json (UXD owns the text): the
// few keys the server needs to build the copy-to-Zalo quote text (getQuoteText, US-083 AC2). A key missing
// in a locale falls back to `en` and is listed in `missing` (reported to UXD) – never invented here.
// The Docker build does not read design/, so the output is committed; `--check` (run by
// test/be-b-s2-units.test.ts) fails when the committed file is stale.
//
//   node scripts/gen-quote-copy.mjs          write the file
//   node scripts/gen-quote-copy.mjs --check  exit 1 when the file differs from the copy
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = join(here, '..');
const copyDir = join(apiDir, '..', '..', 'design', 'copy');
const outPath = join(apiDir, 'src', 'generated', 'quote-copy.ts');

const KEYS = [
  'sale.quote_text',
  'sale.quote_text_extra_guest',
  'occ.adults_short',
  'occ.children_short',
  'occ.under6_short',
];
const LOCALES = ['vi', 'en', 'ru'];

export async function build() {
  const strings = {};
  const missing = {};
  const files = Object.fromEntries(
    LOCALES.map((l) => [l, JSON.parse(readFileSync(join(copyDir, `strings-${l}.json`), 'utf8'))]),
  );
  for (const l of LOCALES) {
    strings[l] = {};
    for (const k of KEYS) {
      const v = files[l][k] ?? files.en[k];
      if (typeof v !== 'string') throw new Error(`copy key ${k} missing in en`);
      if (files[l][k] === undefined) (missing[l] ??= []).push(k);
      strings[l][k] = v;
    }
  }
  const src =
    '// GENERATED by scripts/gen-quote-copy.mjs from design/copy/strings-*.json – do not edit.\n' +
    `export const QUOTE_COPY = ${JSON.stringify(strings, null, 2)} as const;\n\n` +
    '/** Keys a locale lacks (fell back to en) – for UXD. */\n' +
    `export const QUOTE_COPY_MISSING: Record<string, readonly string[]> = ${JSON.stringify(missing, null, 2)};\n`;
  const require = createRequire(import.meta.url);
  const prettier = require('prettier');
  const config = (await prettier.resolveConfig(outPath)) ?? {};
  return prettier.format(src, { ...config, parser: 'typescript' });
}

const out = await build();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    current = '';
  }
  if (current !== out) {
    console.error('src/generated/quote-copy.ts is stale – run node scripts/gen-quote-copy.mjs');
    process.exit(1);
  }
  console.log('quote-copy.ts is up to date');
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath}`);
}
