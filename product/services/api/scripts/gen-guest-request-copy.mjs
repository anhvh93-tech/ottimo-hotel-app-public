#!/usr/bin/env node
// Generates src/generated/guest-request-copy.ts from design/copy/strings-{vi,en,ru}.json (UXD owns the text):
// the texts the server writes into `GuestRequestForGuest` (US-109, US-112, EP14 3.3, 4.3) – `statusLabel`
// (guest.req.status.*) and the out-of-hours `autoReply` (guest.req.auto_reply, params {time}, {open_time},
// {phone}). A key missing in a locale falls back to `en` and is listed in `missing` (reported to UXD);
// OPTIONAL keys missing everywhere are left out (the server then omits the field) – never invented here.
// The Docker build does not read design/, so the output is committed; `--check` (run by
// test/be-d-s4-units.test.ts) fails when the committed file is stale.
//
//   node scripts/gen-guest-request-copy.mjs          write the file
//   node scripts/gen-guest-request-copy.mjs --check  exit 1 when the file differs from the copy
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = join(here, '..');
const copyDir = join(apiDir, '..', '..', 'design', 'copy');
const outPath = join(apiDir, 'src', 'generated', 'guest-request-copy.ts');

const REQUIRED = [
  'guest.req.status.new',
  'guest.req.status.acknowledged',
  'guest.req.status.in_progress',
  'guest.req.status.done',
  'guest.req.status.declined',
];
const OPTIONAL = ['guest.req.auto_reply'];
const LOCALES = ['vi', 'en', 'ru'];

export async function build() {
  const strings = {};
  const missing = {};
  const files = Object.fromEntries(
    LOCALES.map((l) => [l, JSON.parse(readFileSync(join(copyDir, `strings-${l}.json`), 'utf8'))]),
  );
  for (const l of LOCALES) {
    strings[l] = {};
    for (const k of [...REQUIRED, ...OPTIONAL]) {
      const v = files[l][k] ?? files.en[k];
      if (typeof v !== 'string') {
        if (REQUIRED.includes(k)) throw new Error(`copy key ${k} missing in en`);
        (missing[l] ??= []).push(k);
        continue;
      }
      if (files[l][k] === undefined) (missing[l] ??= []).push(k);
      strings[l][k] = v;
    }
  }
  const src =
    '// GENERATED by scripts/gen-guest-request-copy.mjs from design/copy/strings-*.json – do not edit.\n' +
    `export const GUEST_REQUEST_COPY: Record<string, Record<string, string>> = ${JSON.stringify(strings, null, 2)};\n\n` +
    '/** Keys a locale lacks (fell back to en, or left out when optional) – for UXD. */\n' +
    `export const GUEST_REQUEST_COPY_MISSING: Record<string, readonly string[]> = ${JSON.stringify(missing, null, 2)};\n`;
  const require = createRequire(import.meta.url);
  const prettier = require('prettier');
  const config = (await prettier.resolveConfig(outPath)) ?? {};
  return prettier.format(src, { ...config, parser: 'typescript' });
}

const out = await build();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    current = '';
  }
  if (current !== out) {
    console.error(
      'src/generated/guest-request-copy.ts is stale – run node scripts/gen-guest-request-copy.mjs',
    );
    process.exit(1);
  }
  console.log('guest-request-copy.ts is up to date');
} else {
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath}`);
}
