/* OTTIMO hi-fi prototype helpers – DS v0.3 (R2 Đợt 0). Static demo only, not production code.
   - i18n: [data-i18n="key"] (+ data-i18n-args JSON) from window.OTTIMO_STRINGS (../../wireframes/assets/strings.js,
     GENERATED by tools/gen_strings.py). Staff UI R2 = VI + EN (RU at R3, US-115). Fallback EN -> VI, marks lang.
     [data-i18n-ph="key"] sets placeholder, [data-i18n-label="key"] sets aria-label.
   - States: [data-set-state] toggles [data-state] on data-target (default .stateful).
   - Theme: [data-set-theme]. Language: [data-set-lang].
   - Dialogs: [data-open="#id"] opens a native <dialog> (focus trap, inert background, Esc);
     a dialog containing a form that was edited asks "Bỏ các thay đổi chưa lưu?" before closing (DS §6.2);
     focus returns to the opener (DS C15, WCAG 2.4.3).
   - Seg / switch / stepper / tabs demos. Occupancy calculator for booking/quote forms (BR-110, ESC-014).
   - R2 Sprint 3: surcharge preview [data-sur] (BR-411/412/414, ân hạn 12:30), [data-enables] checkbox → nút.
   - R2 Sprint 4 (H19–H24): [data-countdown] toast Hoàn tác 10 giây (gửi trễ – lệnh nằm trong hàng đợi 10 giây rồi mới gửi),
     [data-undo-start] bắt đầu lại, [data-undo] hủy lệnh; [data-filter] lọc thẻ căn theo [data-kind];
     [data-checklist] đếm mục bắt buộc đã tick → mở [data-checklist-submit]; [data-unhide] hiện phần tử (mô phỏng sự kiện SSE). */
(function () {
  var S = window.OTTIMO_STRINGS || { vi: {}, en: {} };
  var LANG = 'vi';
  function fmt(str, a) { return String(str).replace(/\{(\w+)\}/g, function (m, k) { return a && k in a ? a[k] : m; }); }
  function t(key, args, lang) {
    lang = lang || LANG;
    var v = (S[lang] && S[lang][key]) || S.en[key] || S.vi[key];
    return v === undefined ? key : fmt(v, args);
  }
  function argsOf(el) { try { return JSON.parse(el.getAttribute('data-i18n-args') || '{}'); } catch (e) { return {}; } }
  function setLang(lang) {
    LANG = lang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      el.textContent = t(k, argsOf(el));
      var has = S[lang] && S[lang][k] !== undefined;
      if (lang !== 'vi' && !has) { el.setAttribute('lang', S.en[k] !== undefined ? 'en' : 'vi'); el.setAttribute('data-fallback', '1'); }
      else { el.removeAttribute('lang'); el.removeAttribute('data-fallback'); }
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
    document.querySelectorAll('[data-i18n-label]').forEach(function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-label'), argsOf(el))); });
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('[data-set-lang]').forEach(function (b) { b.setAttribute('aria-pressed', String(b.getAttribute('data-set-lang') === lang)); });
    occAll(); surAll();
  }

  /* ---------- occupancy (BR-110 v0.3 + ESC-014: max = base + 1, sofa) ---------- */
  var VND = function (n) { return n.toLocaleString('vi-VN').replace(/,/g, '.'); };
  function occ(form) {
    var get = function (n) { var o = form.querySelector('[data-occ="' + n + '"] output'); return o ? parseInt(o.textContent, 10) || 0 : 0; };
    var roomSel = form.querySelector('[data-occ-room]');
    var opt = roomSel && roomSel.options ? roomSel.options[roomSel.selectedIndex] : roomSel;
    var base = parseInt((opt && opt.getAttribute('data-base')) || form.getAttribute('data-base') || '2', 10);
    var max = parseInt((opt && opt.getAttribute('data-max')) || form.getAttribute('data-max') || '3', 10);
    var room = (opt && (opt.getAttribute('data-room') || opt.value)) || '';
    var nights = parseInt(form.getAttribute('data-nights') || '1', 10);
    var ota = form.getAttribute('data-channel') === 'ota';
    var adults = get('adults'), kids = get('c611'), under6 = get('u6');
    var counted = adults + kids, over = Math.max(0, counted - base);
    var overKids = Math.min(over, kids), overAdults = over - overKids; // adults fill the base first (BR-110)
    var fee = (overKids * 100000 + overAdults * 150000) * nights;
    var field = form.querySelector('[data-occ-field]');
    var out = form.querySelector('[data-occ-summary]');
    var err = form.querySelector('[data-occ-error]');
    var kit = form.querySelector('[data-occ-kit]');
    var feeRow = form.querySelector('[data-occ-fee]');
    if (out) out.textContent = t('occ.summary', { counted: counted, base: base, max: max, under6: under6 });
    var tooMany = counted > max;
    if (field) field.classList.toggle('invalid', tooMany);
    if (err) { err.hidden = !tooMany; var et = err.querySelector('[data-i18n]'); if (et) { et.setAttribute('data-i18n-args', JSON.stringify({ room: room, max: max })); et.textContent = t('error.CAPACITY_EXCEEDED', { room: room, max: max }); } }
    if (kit) { kit.hidden = tooMany || over === 0; var kt = kit.querySelector('[data-i18n]'); if (kt) { kt.setAttribute('data-i18n-args', JSON.stringify({ n: over })); kt.textContent = t('occ.kit_reminder', { n: over }); } }
    if (feeRow) {
      feeRow.hidden = tooMany || over === 0;
      var lab = feeRow.querySelector('[data-occ-fee-label]'), val = feeRow.querySelector('[data-occ-fee-value]');
      if (lab) { var k = ota ? 'occ.fee_ota' : 'occ.fee_line'; lab.setAttribute('data-i18n', k); lab.setAttribute('data-i18n-args', JSON.stringify({ n: over, nights: nights })); lab.textContent = t(k, { n: over, nights: nights }); }
      if (val) val.textContent = ota ? '0' : VND(fee);
    }
    var tot = form.querySelector('[data-occ-total]'), roomAmt = parseInt(form.getAttribute('data-room-amount') || '0', 10);
    if (tot && roomAmt) tot.textContent = VND(roomAmt + (ota || tooMany ? 0 : fee)) + ' đ';
    form.querySelectorAll('[data-occ-submit]').forEach(function (b) { if (tooMany) b.setAttribute('aria-disabled', 'true'); else b.removeAttribute('aria-disabled'); });
  }
  function occAll() { document.querySelectorAll('[data-occ-form]').forEach(occ); }

  /* ---------- surcharge preview (R2 Sprint 3): BR-411 nhận sớm, BR-412 trả muộn + ân hạn 12:30, BR-414 chủ động, BR-416/417 ----------
     <div data-sur="early|late" data-base-rate="750000" [data-prev-night="14/10"]>
       <input data-sur-time value="11:00"> · [role=switch data-sur-arrival] (late: căn có khách đến cùng ngày → bỏ ân hạn)
       <p data-sur-out data-i18n=…> · [data-sur-ack] (tick "đã báo khách", hiện khi có phụ thu) · [data-sur-ext] (chuyển gia hạn / thêm đêm)
     Demo only – server (previewCheckIn / setLateCheckout dryRun) is the source of truth. Rounding to 1.000 đ as BR-415 example. */
  function mins(v) { var m = /^(\d{1,2}):(\d{2})$/.exec((v || '').trim()); return m ? (+m[1]) * 60 + (+m[2]) : null; }
  function sur(box) {
    var kind = box.getAttribute('data-sur'), base = parseInt(box.getAttribute('data-base-rate') || '0', 10);
    var inp = box.querySelector('[data-sur-time]'), out = box.querySelector('[data-sur-out]');
    var tm = mins(inp && inp.value); if (!out) return;
    if (inp) inp.closest('.field') && inp.closest('.field').classList.toggle('invalid', tm === null);
    if (tm === null) return;
    var key, args = {}, pct = 0, ext = false;
    if (kind === 'early') {
      if (tm >= 14 * 60) { key = 'sur.early_zero'; args = { std: '14:00' }; }
      else if (tm >= 10 * 60) pct = 30; else if (tm >= 6 * 60) pct = 50;
      else { key = 'sur.early_extra_night'; args = { date: box.getAttribute('data-prev-night') || '' }; ext = true; }
      if (pct) { key = 'sur.early_fee'; }
    } else {
      var sw = box.querySelector('[data-sur-arrival]'), arrival = !!sw && sw.getAttribute('aria-checked') === 'true';
      if (tm <= 12 * 60) key = 'late.std_zero';
      else if (!arrival && tm <= 12 * 60 + 30) key = 'late.fee_zero';
      else if (tm <= 15 * 60) pct = 30; else if (tm <= 18 * 60) pct = 50;
      else { key = 'late.treat_as_extension'; args = { time: '18:00' }; ext = true; }
      if (pct) key = 'late.fee';
      box.querySelectorAll('[data-sur-grace]').forEach(function (g) { g.hidden = !arrival; });
    }
    if (pct) { args = { amount: VND(Math.round(base * pct / 100 / 1000) * 1000), pct: pct }; }
    out.setAttribute('data-i18n', key); out.setAttribute('data-i18n-args', JSON.stringify(args)); out.textContent = t(key, args);
    out.classList.toggle('pos', !!pct);
    box.querySelectorAll('[data-sur-ack]').forEach(function (a) { a.hidden = !pct; var c = a.querySelector('input'); if (c && !pct) c.checked = false; });
    box.querySelectorAll('[data-sur-ext]').forEach(function (a) { a.hidden = !ext; });
    box.querySelectorAll('[data-sur-submit]').forEach(function (b) { var ok = !ext && (!pct || (box.querySelector('[data-sur-ack] input') || {}).checked); if (ok) b.removeAttribute('aria-disabled'); else b.setAttribute('aria-disabled', 'true'); });
  }
  function surAll() { document.querySelectorAll('[data-sur]').forEach(sur); }

  /* ---------- dialogs ---------- */
  var openers = new WeakMap();
  function openDlg(sel, opener) {
    var d = document.querySelector(sel); if (!d || typeof d.showModal !== 'function') return;
    openers.set(d, opener); d.removeAttribute('data-dirty'); d.showModal();
    var h = d.querySelector('[autofocus]') || d.querySelector('h2'); if (h) { if (!h.hasAttribute('tabindex') && h.tagName === 'H2') h.setAttribute('tabindex', '-1'); h.focus(); }
  }
  function closeDlg(d, force) {
    if (!force && d.getAttribute('data-dirty') === '1' && d.id !== 'dlg-unsaved') {
      var u = document.getElementById('dlg-unsaved');
      if (u) { u._target = d; openers.set(u, document.activeElement); u.showModal(); return; }
    }
    d.close(); var o = openers.get(d); if (o && o.focus) o.focus();
  }
  document.addEventListener('input', function (e) { var d = e.target.closest('dialog'); if (d) d.setAttribute('data-dirty', '1'); var sb = e.target.matches('[data-sur-time]') && e.target.closest('[data-sur]'); if (sb) sur(sb); });
  document.addEventListener('cancel', function (e) { var d = e.target; if (d.tagName === 'DIALOG') { e.preventDefault(); closeDlg(d); } }, true);

  document.addEventListener('click', function (e) {
    var el;
    if ((el = e.target.closest('[data-open]'))) { e.preventDefault(); openDlg(el.getAttribute('data-open'), el); return; }
    if ((el = e.target.closest('[data-close]'))) {
      var d = el.closest('dialog'); if (!d) return;
      if (d.id === 'dlg-unsaved') { var target = d._target; d.close(); if (el.getAttribute('data-close') === 'discard' && target) closeDlg(target, true); else if (target) { var f = target.querySelector('input,select,textarea'); if (f) f.focus(); } return; }
      closeDlg(d, el.getAttribute('data-close') === 'force'); return;
    }
    if ((el = e.target.closest('[data-set-state]'))) {
      var st = el.getAttribute('data-set-state'), sel = el.getAttribute('data-target') || '.stateful';
      document.querySelectorAll(sel).forEach(function (x) { x.setAttribute('data-state', st); });
      el.parentElement.querySelectorAll('[data-set-state]').forEach(function (x) { x.setAttribute('aria-pressed', String(x === el)); });
      var live = document.getElementById('doc-live'); if (live) live.textContent = el.textContent.trim();
      return;
    }
    if ((el = e.target.closest('[data-set-theme]'))) {
      var v = el.getAttribute('data-set-theme');
      if (v === 'auto') document.documentElement.removeAttribute('data-theme'); else document.documentElement.setAttribute('data-theme', v);
      el.parentElement.querySelectorAll('[data-set-theme]').forEach(function (x) { x.setAttribute('aria-pressed', String(x === el)); });
      return;
    }
    if ((el = e.target.closest('[data-set-lang]'))) { setLang(el.getAttribute('data-set-lang')); return; }
    if ((el = e.target.closest('[role="switch"]'))) {
      var on = el.getAttribute('aria-checked') !== 'true'; el.setAttribute('aria-checked', String(on));
      var r = el.getAttribute('data-reveal'); if (r) document.querySelectorAll(r).forEach(function (x) { x.hidden = !on; });
      var c = el.getAttribute('data-conceal'); if (c) document.querySelectorAll(c).forEach(function (x) { x.hidden = on; });
      var sb2 = el.closest('[data-sur]'); if (sb2) sur(sb2);
      return;
    }
    if ((el = e.target.closest('.stepper button'))) {
      var out = el.parentElement.querySelector('output'), n = parseInt(out.textContent, 10) || 0;
      var min = parseInt(el.parentElement.getAttribute('data-min') || '0', 10), max = parseInt(el.parentElement.getAttribute('data-max') || '9', 10);
      n = el.getAttribute('data-d') === '-1' ? Math.max(min, n - 1) : Math.min(max, n + 1); out.textContent = n;
      var f = el.closest('[data-occ-form]'); if (f) occ(f);
      var d2 = el.closest('dialog'); if (d2) d2.setAttribute('data-dirty', '1');
      return;
    }
    if ((el = e.target.closest('.seg button'))) {
      if (el.hasAttribute('data-set-state') || el.hasAttribute('data-set-lang') || el.hasAttribute('data-set-theme')) return;
      el.parentElement.querySelectorAll('button').forEach(function (x) { x.setAttribute('aria-pressed', String(x === el)); });
      var ch = el.getAttribute('data-channel'); var form = el.closest('[data-occ-form]');
      if (ch && form) { form.setAttribute('data-channel', ch); occ(form); }
      var show = el.getAttribute('data-show-only'); if (show) { var grp = el.closest('[data-seg-scope]') || document; grp.querySelectorAll('[data-seg-pane]').forEach(function (p) { p.hidden = p.getAttribute('data-seg-pane') !== show; }); }
      return;
    }
    if ((el = e.target.closest('[role="tab"]'))) {
      var list = el.closest('[role="tablist"]');
      list.querySelectorAll('[role="tab"]').forEach(function (x) { var s = x === el; x.setAttribute('aria-selected', String(s)); x.tabIndex = s ? 0 : -1; var p = document.getElementById(x.getAttribute('aria-controls')); if (p) p.hidden = !s; });
      return;
    }
    if ((el = e.target.closest('[aria-disabled="true"]'))) { e.preventDefault(); e.stopPropagation(); }
  }, true);

  document.addEventListener('change', function (e) {
    var f = e.target.closest('[data-occ-form]'); if (f && e.target.matches('[data-occ-room]')) occ(f);
    var sb = e.target.closest('[data-sur]'); if (sb && e.target.matches('[data-sur-ack] input')) sur(sb);
    /* [data-enables="#id"] checkbox/radio: bật nút khi đã tick (vd. "Tôi đã báo khách", chọn đồng ý Có/Không) */
    var en = e.target.getAttribute && e.target.getAttribute('data-enables');
    if (en) document.querySelectorAll(en).forEach(function (b) { if (e.target.checked) b.removeAttribute('aria-disabled'); else b.setAttribute('aria-disabled', 'true'); });
  });
  // Roving arrow keys for tablists (WAI-ARIA APG)
  document.addEventListener('keydown', function (e) {
    var tab = e.target.closest && e.target.closest('[role="tab"]'); if (!tab) return;
    if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return;
    var tabs = Array.prototype.slice.call(tab.closest('[role="tablist"]').querySelectorAll('[role="tab"]'));
    var i = tabs.indexOf(tab) + (e.key === 'ArrowRight' ? 1 : -1); i = (i + tabs.length) % tabs.length; tabs[i].focus(); tabs[i].click();
  });

  /* ---------- R2 Sprint 4: hoàn tác 10 giây (gửi trễ), bộ lọc, checklist, mô phỏng SSE ---------- */
  var timers = new WeakMap();
  function cdRender(box, n) {
    box.querySelectorAll('[data-cd-label]').forEach(function (el) {
      var k = el.getAttribute('data-i18n'); el.setAttribute('data-i18n-args', JSON.stringify({ s: n })); el.textContent = t(k, { s: n });
    });
  }
  function cdStart(box) {
    if (!box) return; clearInterval(timers.get(box)); box.hidden = false;
    var n = parseInt(box.getAttribute('data-countdown') || '10', 10); cdRender(box, n);
    timers.set(box, setInterval(function () {
      n -= 1; cdRender(box, Math.max(n, 0));
      if (n <= 0) { clearInterval(timers.get(box)); box.hidden = true; var live = document.getElementById('doc-live'); if (live) live.textContent = t('hk.sent_after_undo'); }
    }, 1000));
  }
  document.addEventListener('click', function (e) {
    var el;
    if ((el = e.target.closest('[data-undo-start]'))) { cdStart(document.querySelector(el.getAttribute('data-undo-start'))); return; }
    if ((el = e.target.closest('[data-undo]'))) {
      var box = el.closest('[data-countdown]'); if (box) { clearInterval(timers.get(box)); box.hidden = true; }
      var live = document.getElementById('doc-live'); if (live) live.textContent = t('hk.undone'); return;
    }
    if ((el = e.target.closest('[data-filter]'))) {
      var scope = el.closest('[data-filter-scope]') || document, f = el.getAttribute('data-filter');
      el.parentElement.querySelectorAll('[data-filter]').forEach(function (b) { b.setAttribute('aria-pressed', String(b === el)); });
      scope.querySelectorAll('[data-kind]').forEach(function (c) { c.hidden = f !== 'all' && (' ' + c.getAttribute('data-kind') + ' ').indexOf(' ' + f + ' ') < 0; });
      return;
    }
    if ((el = e.target.closest('[data-unhide]'))) {
      document.querySelectorAll(el.getAttribute('data-unhide')).forEach(function (x) { x.hidden = false; x.classList.remove('is-new'); void x.offsetWidth; x.classList.add('is-new'); });
      var lv = document.getElementById('doc-live'); if (lv && el.getAttribute('data-announce')) lv.textContent = t(el.getAttribute('data-announce'));
    }
  });
  function checklist(box) {
    var req = box.querySelectorAll('input[type=checkbox][data-req]'), done = 0;
    req.forEach(function (c) { if (c.checked) done++; });
    box.querySelectorAll('[data-checklist-count]').forEach(function (o) { var k = o.getAttribute('data-i18n'); var a = { n: done, total: req.length }; o.setAttribute('data-i18n-args', JSON.stringify(a)); o.textContent = t(k, a); });
    box.querySelectorAll('[data-checklist-submit]').forEach(function (b) { if (done === req.length) b.removeAttribute('aria-disabled'); else b.setAttribute('aria-disabled', 'true'); });
  }
  document.addEventListener('change', function (e) { var b = e.target.closest('[data-checklist]'); if (b) checklist(b); });
  document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('[data-checklist]').forEach(checklist);
    document.querySelectorAll('[data-countdown][data-autostart]').forEach(cdStart);
  });

  document.addEventListener('DOMContentLoaded', function () { setLang(document.documentElement.getAttribute('data-init-lang') || 'vi'); });
  window.OTTIMO_HIFI = { setLang: setLang, t: t, occ: occ, sur: sur, open: openDlg };
})();
