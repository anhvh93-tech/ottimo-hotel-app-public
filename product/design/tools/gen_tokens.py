def rgb(h):
    h = h.lstrip('#'); return [int(h[i:i+2], 16) for i in (0, 2, 4)]


def mix(a, b, t):
    """Single-ratio blend: (1 - t)·a + t·b on all three sRGB channels (t = share of b). No new hue."""
    A, B = rgb(a), rgb(b)
    return "#" + "".join(f"{round(A[i] + (B[i] - A[i]) * t):02X}" for i in range(3))


