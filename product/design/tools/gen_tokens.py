def palettes():
    brand = {f"brand-{k}": v for k, v, _, _ in BRAND}
    light = {c[0]: c[1] for c in COLORS}
    dark = {c[0]: c[2] for c in COLORS}
    light.update(brand); dark.update(brand)
    return light, dark


def build():
    light, dark = palettes()
    rows = []
    fails = 0
    for fg, bg, kind, where in PAIRS:
        res = []
        for pal in (light, dark):
            r = cr(pal[fg], pal[bg])
            if kind == "info-only":
                ok = None
            else:
                need = 4.5 if kind in ("text", "forbidden") else 3.0
                ok = r >= need
                if ok is False and kind != "forbidden":
                    fails += 1
            res.append((r, ok))
        rows.append((fg, bg, kind, where, res))
    return light, dark, rows, fails


