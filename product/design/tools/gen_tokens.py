def tint_audit():
    """Best single ratio t of each declared tint/shade and its distance (8-bit RGB) from that exact blend."""
    light, dark = palettes()
    rows, tint_fails = [], 0
    for tok, mode, a, b in TINT:
        T, A, B = rgb((light if mode == "light" else dark)[tok]), rgb(BR[a]), rgb(BR[b])
        den = sum((B[i] - A[i]) ** 2 for i in range(3))
        t = max(0.0, min(1.0, sum((T[i] - A[i]) * (B[i] - A[i]) for i in range(3)) / den))
        dist = math.dist([A[i] + t * (B[i] - A[i]) for i in range(3)], T)
        if dist <= TINT_TOL:
            verdict = "khớp"
        elif (tok, mode) in TINT_EXCEPTIONS:
            verdict = "ngoại lệ 2.4 – " + TINT_EXCEPTIONS[(tok, mode)]
        else:
            verdict = "**LỆCH – chưa khai ở 2.4**"
            tint_fails += 1
        rows.append((tok, mode, a, b, t, dist, verdict))
    return rows, tint_fails


