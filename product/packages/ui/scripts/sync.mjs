// Copies the OTTIMO line icons (UXD source: design/wireframes/assets/icons.js) into src/icons.ts.
// Run `pnpm --filter @ottimo/ui sync` after UXD changes icons; icons.test.ts fails CI when stale.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

export const SRC_URL = new URL('../../../design/wireframes/assets/icons.js', import.meta.url);
export const OUT_URL = new URL('../src/icons.ts', import.meta.url);

export async function render() {
  const js = await readFile(SRC_URL, 'utf8');
  const entries = [...js.matchAll(/^\s+([a-z][a-z0-9]*): '([^']*)'/gm)].map((m) => [m[1], m[2]]);
  const body = entries.map(([k, v]) => `  ${k}: '${v}',`).join('\n');
  const source =
    '// GENERATED by packages/ui/scripts/sync.mjs from design/wireframes/assets/icons.js – do not edit.\n' +
    '// 24x24 line icons, stroke 1.7 (DS v0.3). Decorative unless labelled; meaning is always repeated in text.\n' +
    `export const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`;
  const options = (await prettier.resolveConfig(fileURLToPath(OUT_URL))) ?? {};
  return prettier.format(source, { ...options, parser: 'typescript' });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUT_URL, await render());
  console.log('icons.ts written');
}
