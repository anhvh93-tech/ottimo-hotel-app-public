describe('encodeQr (SEC F2 – QR drawn in the bundle)', () => {
  it('matches an independent encoder module for module (VietQR payload, v7, mask 2)', () => {
    const m = encodeQr(VIETQR_SAMPLE, { mask: 2 });
    expect(m.version).toBe(7);
    expect(m.modules.map((r) => r.map((b) => (b ? '1' : '0')).join(''))).toEqual(EXPECTED_V7_MASK2);
  });

  it('picks the smallest version that fits and a mask 0–7', () => {
    expect(encodeQr('HELLO').version).toBe(1);
    expect(encodeQr('B'.repeat(300)).version).toBe(13);
    const m = encodeQr(VIETQR_SAMPLE);
    expect(m.mask).toBeGreaterThanOrEqual(0);
    expect(m.mask).toBeLessThan(8);
  });

  it('draws an SVG path with a quiet zone and rejects payloads above version 20', () => {
    const path = qrSvgPath(encodeQr('HELLO'));
    expect(path.startsWith('M4 4h1v1h-1z')).toBe(true);
    expect(() => encodeQr('x'.repeat(1000))).toThrow();
  });
});
